def main():
    creators = [
        avatar_darth_vader,
        avatar_ben10,
        avatar_batman,
        avatar_captain_america,
        avatar_harry_potter,
        avatar_spiderman,
        avatar_wonder_woman,
        avatar_elsa,
        avatar_peach,
        avatar_harley_quinn,
    ]

    names = [
        "Darth Vader",
        "Ben 10",
        "Batman",
        "Capitão América",
        "Harry Potter",
        "Homem-Aranha",
        "Mulher-Maravilha",
        "Elsa",
        "Princesa Peach",
        "Arlequina"
    ]

    images = [fn() for fn in creators]

    # Grade 5x2.
    cell_w, cell_h, pad, label_h = 220, 244, 18, 34

    sheet = Image.new(
        "RGB",
        (pad + 5*(cell_w+pad),
         pad + 2*(cell_h+label_h+pad)),
        "#0b0d12"
    )

    sd = ImageDraw.Draw(sheet)

    try:
        label_font = (
            ImageFont.truetype(FONT_PATH, 15)
            if FONT_PATH else ImageFont.load_default()
        )
    except OSError:
        label_font = ImageFont.load_default()

    for i, (im, name) in enumerate(zip(images, names)):
        col, row = i % 5, i // 5
        x = pad + col*(cell_w+pad)
        y = pad + row*(cell_h+label_h+pad)

        thumb = im.resize(
            (cell_w, cell_h),
            Image.Resampling.LANCZOS
        )

        sheet.paste(thumb, (x, y))

        sd.text(
            (x+cell_w//2, y+cell_h+17),
            name,
            font=label_font,
            fill="#f2f1ee",
            anchor="mm"
        )

    sheet.save(OUT / "grade_10_avatares.png")

    print(f"Avatares salvos em: {OUT}")
    print(f"Prévia: {OUT / 'grade_10_avatares.png'}")


if __name__ == "__main__":
    main()
