
"""Gera 10 avatares geométricos inspirados em personagens da cultura pop.

Requisitos: Python 3 e Pillow (pip install pillow)
Execução: python avatares_geometricos.py

O script salva 10 PNGs individuais e uma prévia em grade na pasta
'avatares_geometricos', ao lado deste arquivo.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import math

SCALE = 3
SIZE = 256
OUT = Path(__file__).resolve().parent / "avatares_geometricos"
OUT.mkdir(exist_ok=True)

FONT_CANDIDATES = [
    "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
    "/usr/share/fonts/truetype/liberation2/LiberationSans-Bold.ttf",
    "C:/Windows/Fonts/arialbd.ttf",
]
FONT_PATH = next((p for p in FONT_CANDIDATES if Path(p).exists()), None)


class Avatar:
    def __init__(self):
        self.im = Image.new("RGB", (SIZE*SCALE, SIZE*SCALE), "#07090e")
        self.d = ImageDraw.Draw(self.im)
        self.background()

    def background(self):
        for x in range(-SIZE, SIZE*2, 28):
            self.line([(x, 0), (x+SIZE, SIZE)], "#151820", 1)
            self.line([(x, SIZE), (x+SIZE, 0)], "#12151c", 1)
        self.ellipse((15, 8, 241, 248), "#0a0c12")

    def _box(self, box):
        return tuple(int(v*SCALE) for v in box)

    def poly(self, pts, fill, outline=None, width=1):
        pts = [(int(x*SCALE), int(y*SCALE)) for x, y in pts]
        self.d.polygon(pts, fill=fill)
        if outline:
            self.d.line(
                pts+[pts[0]], fill=outline,
                width=max(1, int(width*SCALE)), joint="curve"
            )

    def ellipse(self, box, fill, outline=None, width=1):
        self.d.ellipse(
            self._box(box), fill=fill, outline=outline,
            width=max(1, int(width*SCALE)) if outline else 1
        )

    def rr(self, box, radius, fill, outline=None, width=1):
        self.d.rounded_rectangle(
            self._box(box), radius=int(radius*SCALE), fill=fill,
            outline=outline,
            width=max(1, int(width*SCALE)) if outline else 1
        )

    def line(self, pts, fill, width=2):
        pts = [(int(x*SCALE), int(y*SCALE)) for x, y in pts]
        self.d.line(
            pts, fill=fill,
            width=max(1, int(width*SCALE)), joint="curve"
        )

    def arc(self, box, start, end, fill, width=2):
        self.d.arc(
            self._box(box), start, end, fill=fill,
            width=max(1, int(width*SCALE))
        )

    def text(self, xy, value, size, fill, anchor="mm",
             stroke_width=0, stroke_fill=None):
        px = int(size*SCALE)
        if FONT_PATH:
            font = ImageFont.truetype(FONT_PATH, px)
        else:
            font = ImageFont.load_default()

        self.d.text(
            (int(xy[0]*SCALE), int(xy[1]*SCALE)),
            value, font=font, fill=fill, anchor=anchor,
            stroke_width=int(stroke_width*SCALE),
            stroke_fill=stroke_fill
        )

    def finish(self, filename):
        final = self.im.resize((512, 512), Image.Resampling.LANCZOS)
        final.save(OUT / filename)
        return final


# Paleta comum
SKIN = "#f1d8c5"
SKIN_SHADE = "#d6ad9a"
INK = "#171820"
WHITE = "#f7f4f0"


def _shade(hex_color, amount):
    h = hex_color.lstrip('#')
    r, g, b = (int(h[i:i+2], 16) for i in (0, 2, 4))
    r = max(0, min(255, r+amount))
    g = max(0, min(255, g+amount))
    b = max(0, min(255, b+amount))
    return f"#{r:02x}{g:02x}{b:02x}"


def base_shoulders(a, color, collar=None):
    a.poly(
        [(27,256),(30,211),(47,184),(78,171),(178,171),
         (209,184),(226,211),(229,256)], color
    )
    a.poly(
        [(27,256),(30,211),(47,184),(67,183),(84,256)],
        _shade(color, -12)
    )
    a.poly(
        [(229,256),(226,211),(209,184),(189,183),(172,256)],
        _shade(color, -10)
    )
    if collar:
        a.poly(
            [(91,170),(128,194),(165,170),(153,207),
             (128,220),(103,207)], collar
        )


def face(a, skin=SKIN):
    a.ellipse((59,48,197,170), skin)
    a.ellipse((52,91,79,133), _shade(skin,-10))
    a.ellipse((177,91,204,133), _shade(skin,-10))
    a.ellipse((63,98,76,121), skin)
    a.ellipse((180,98,193,121), skin)


def simple_face(a, eye_color="#38343a", mouth="#9d5c60"):
    a.ellipse((91,104,105,112), eye_color)
    a.ellipse((151,104,165,112), eye_color)
    a.line([(128,111),(124,128),(130,130)], SKIN_SHADE, 2)
    a.arc((112,130,144,150), 8, 170, mouth, 2)


def star(a, cx, cy, r, color):
    pts = []
    for i in range(10):
        ang = -math.pi/2+i*math.pi/5
        rad = r if i % 2 == 0 else r*0.43
        pts.append((
            cx+math.cos(ang)*rad,
            cy+math.sin(ang)*rad
        ))
    a.poly(pts, color)


